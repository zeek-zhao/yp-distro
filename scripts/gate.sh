#!/usr/bin/env bash
# S8 提交前门禁：五项硬约束机械检查（DES-009 / AGENTS §3），不跑 bitbake
# 用法：bash scripts/gate.sh   —— 全部通过打印 GATE_PASS 并 exit 0；任一失败 exit 1
set -uo pipefail

cd "$(git rev-parse --show-toplevel 2>/dev/null || pwd)"

FAIL=0
pass() { echo "  [PASS] $1"; }
fail() { echo "  [FAIL] $1" >&2; FAIL=1; }

echo "===== S8 GATE ====="

# G1 脚本语法：全部 .sh 做 bash -n
echo "--- G1 脚本语法 (bash -n) ---"
g1_count=0; g1_bad=0
while IFS= read -r f; do
  g1_count=$((g1_count+1))
  if ! bash -n "$f" 2>/dev/null; then fail "G1 $f 语法错误"; g1_bad=$((g1_bad+1)); fi
done < <(find scripts -type f -name '*.sh' | sort)
[ "$g1_bad" -eq 0 ] && pass "G1 全部 $g1_count 个脚本 bash -n 通过"

# G2 阈值唯一性：数值来自 threshold.conf，门禁自身不再含阈值字面量（CHG-009）
# 仅检查两项切分阈值；JENKINS_UID/MIN_FREE_BYTES 是挂载预检契约，由 check-vars 用变量断言
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=cache/threshold.conf
. "$SCRIPT_DIR/cache/threshold.conf"
echo "--- G2 阈值唯一性 ---"
g2_pattern="${SLICE_MAX_BYTES}|${UPLOAD_TIMEOUT_SEC}"
g2_out="$(grep -rnE "$g2_pattern" scripts/ .github/ 2>/dev/null \
  | grep -v '^scripts/cache/threshold.conf:' \
  | grep -vE ':[0-9]+:[[:space:]]*#' || true)"
if [ -n "$g2_out" ]; then
  fail "G2 源码范围出现非 threshold.conf 的阈值定义:"; echo "$g2_out" >&2
else
  pass "G2 源码范围仅 threshold.conf 定义阈值（数值取自唯一源，无门禁自我豁免）"
fi
if [ -x scripts/cache/gen-meta.sh ]; then
  gen="$(bash scripts/cache/gen-meta.sh 2>/dev/null)"
  if diff -q <(echo "$gen") docker/cache-meta.json >/dev/null 2>&1; then
    pass "G2 docker/cache-meta.json 与 gen-meta 生成值一致（生成产物）"
  else
    fail "G2 docker/cache-meta.json 与 gen-meta 生成值不一致（需重新生成）"
  fi
else
  fail "G2 缺少可执行的 scripts/cache/gen-meta.sh"
fi

# G3 无缓存服务器：排除注释行后，不得有真实远程配置
echo "--- G3 无缓存服务器 ---"
g3_real="$(grep -rn "SSTATE_MIRRORS\|hashserv" scripts/ kas/ docker/ .github/ 2>/dev/null \
  | grep -vE ':[0-9]+:[[:space:]]*#|^[[:space:]]*#' \
  | grep -vE '禁止远程缓存服务器|hashserv 数据库落到|本地 hashserv' || true)"
# 真实远程配置特征：SSTATE_MIRRORS 赋值、BB_HASHSERVE 非 auto/非本地、http(s) hashserv URL
g3_bad="$(echo "$g3_real" | grep -iE 'SSTATE_MIRRORS[[:space:]]*=|BB_HASHSERVE[[:space:]]*=.*(http|:)|https?://.*hashserv|hashserv.*https?://' || true)"
if [ -n "$g3_bad" ]; then
  fail "G3 检出远程缓存服务器配置:"; echo "$g3_bad" >&2
else
  pass "G3 无远程缓存服务器配置（本地 BB_HASHSERVE=auto 允许）"
fi

# G4 提交身份与 AI 署名
echo "--- G4 提交身份 / AI 署名 ---"
bad_mail="$(git log --format='%ae' | grep -v '^zeek.zhao@foxmail.com$' | sort -u || true)"
if [ -n "$bad_mail" ]; then
  fail "G4 检出非指定提交身份:"; echo "$bad_mail" >&2
else
  pass "G4 全部提交邮箱为 zeek.zhao@foxmail.com"
fi
ai_trailer="$(git log --format='%B' | grep -iE 'co-authored-by|signed-off-by:.*ai|generated by|🤖' || true)"
if [ -n "$ai_trailer" ]; then
  fail "G4 检出 AI 署名:"; echo "$ai_trailer" >&2
else
  pass "G4 无 AI 署名 trailer"
fi

# G5 文档一致性：traceability 引用的每个判据在 acceptance 中存在（ISS-012：按语义正则提取，不按列切分）
# 不解析 markdown 列（单元格内含 \| 与反引号内的 | 会错位），改为全文提取「判据 N」token 逐个验证
echo "--- G5 文档一致性 (traceability -> acceptance) ---"
g5_bad=0
while IFS= read -r n; do
  [ -z "$n" ] && continue
  # acceptance 判据行形如 "| 6 | ..."
  grep -qE "^\| ${n} \|" docs/m0/acceptance.md || { fail "G5 acceptance 缺判据 $n"; g5_bad=$((g5_bad+1)); }
done < <(grep -oE '判据[[:space:]]*[0-9]+' docs/m0/traceability.md | grep -oE '[0-9]+' | sort -u)
# 反向：acceptance 判据 1-8 每个都被 traceability 引用
while IFS= read -r n; do
  grep -qE "判据[[:space:]]*${n}([^0-9]|$)" docs/m0/traceability.md || { fail "G5 traceability 未引用判据 $n"; g5_bad=$((g5_bad+1)); }
done < <(grep -oE '^\| [1-8] \|' docs/m0/acceptance.md | grep -oE '[1-8]')
[ "$g5_bad" -eq 0 ] && pass "G5 traceability 引用的判据在 acceptance 均存在，且判据 1-8 均被引用"

# G6 构建并发资源化契约（M0.1.2 / CHG-022）：诊断脚本只读 SUGGEST_*，base.yml 按 CPU+cgroup 内存分级
echo "--- G6 构建并发资源化契约 ---"
g6_bad=0
if [ ! -x scripts/build/threads.sh ]; then
  fail "G6 缺少可执行 scripts/build/threads.sh（daemon 级诊断）"; g6_bad=$((g6_bad+1))
else
  for tok in 'RESOURCE_TIER=' 'RESOURCE_MEM_GB=' 'SUGGEST_BUILD_THREADS=' 'SUGGEST_PARALLEL_MAKE=' 'docker info' 'standard'; do
    grep -Fq "$tok" scripts/build/threads.sh || { fail "G6 threads.sh 缺关键契约: $tok"; g6_bad=$((g6_bad+1)); }
  done
  if grep -qE 'export YP_BUILD_THREADS|export YP_PARALLEL_MAKE' scripts/build/threads.sh; then
    fail "G6 threads.sh 仍输出 export YP_（应为只读诊断，ISS-039）"; g6_bad=$((g6_bad+1))
  fi
fi
if grep -qE 'BB_NUMBER_THREADS[[:space:]]*=[[:space:]]*"32"|PARALLEL_MAKE[[:space:]]*=[[:space:]]*"-j 16"' kas/base.yml; then
  fail "G6 kas/base.yml 写死了 32/-j16 默认值（应动态分级）"; g6_bad=$((g6_bad+1))
fi
bbclass='meta-yp-distro/classes/yp-concurrency.bbclass'
if [ ! -f "$bbclass" ]; then
  fail "G6 缺 $bbclass（分级函数所在 .bbclass，ISS-040）"; g6_bad=$((g6_bad+1))
else
  for tok in 'def yp_build_threads(d):' 'def yp_mem_bytes(d):' '/sys/fs/cgroup/memory.max' '/sys/fs/cgroup/memory/memory.limit_in_bytes' '/proc/meminfo'; do
    grep -Fq "$tok" "$bbclass" || { fail "G6 $bbclass 缺关键契约: $tok"; g6_bad=$((g6_bad+1)); }
  done
fi
if ! grep -Fq 'INHERIT += "yp-concurrency"' kas/base.yml; then
  fail "G6 kas/base.yml 未 INHERIT yp-concurrency（CHG-022）"; g6_bad=$((g6_bad+1))
fi
if ! grep -Fq 'BB_NUMBER_THREADS = "${@yp_build_threads(d)}"' kas/base.yml; then
  fail "G6 kas/base.yml 缺 BB_NUMBER_THREADS=yp_build_threads(d) 赋值"; g6_bad=$((g6_bad+1))
fi
if grep -qE 'os\.environ\.get|YP_BUILD_THREADS|YP_PARALLEL_MAKE' kas/base.yml; then
  fail "G6 kas/base.yml 仍有 env 控制变量残留（应为 yp_build_threads(d)，ISS-039）"; g6_bad=$((g6_bad+1))
fi
[ "$g6_bad" -eq 0 ] && pass "G6 threads.sh 只读 SUGGEST_* 诊断在位，base.yml 按 CPU+cgroup 内存动态分级且未写死"

echo "===== GATE RESULT ====="
if [ "$FAIL" -eq 0 ]; then
  echo "GATE_PASS"
  exit 0
else
  echo "GATE_FAIL" >&2
  exit 1
fi
