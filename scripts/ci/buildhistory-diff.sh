#!/usr/bin/env bash
# YP-M1-S4 / DES-005 / D-06: buildhistory 两次构建差异可读并归档。
#
# dev edition 启用 buildhistory（kas/editions/dev.yml），BUILDHISTORY_COMMIT=1
# 后每次构建在 BUILDHISTORY_DIR（git 仓库）留下一个 commit。buildhistory 仓库
# 中的 installed-packages / files-in-package / 文件大小等均为纯文本，
# 用 git diff 对比两次 commit 即得可读差异（不依赖 oe-core 的 buildhistory-diff
# 脚本对 oe-init 环境的挑剔要求；git diff 更稳且语义等价）。
#
# 用法：
#   buildhistory-diff.sh --history-dir <dir> [--rev1 <sha>] [--rev2 <sha>]
#                        [--out <file>] [--check] [--stat]
# 退出：0=成功（--check 时 diff 可读）；1=失败；2=参数/环境错误。
set -uo pipefail

HIST_DIR=""
REV1=""
REV2=""
OUT=""
CHECK=0
STAT=0

usage() {
  echo "usage: buildhistory-diff.sh --history-dir <dir> [opts]"
  echo "  --history-dir <dir>  buildhistory 仓库目录（含 .git）"
  echo "  --rev1 <sha>         基线 commit（默认 HEAD~1）"
  echo "  --rev2 <sha>         对比 commit（默认 HEAD）"
  echo "  --out <file>         diff 归档路径（默认 stdout）"
  echo "  --check              断言两个 commit 均可解析且 diff 可读"
  echo "  --stat               附加 --stat 摘要到归档"
  echo "  --help"
}

while [ $# -gt 0 ]; do
  case "$1" in
    --history-dir) HIST_DIR="${2:-}"; shift 2 ;;
    --rev1) REV1="${2:-}"; shift 2 ;;
    --rev2) REV2="${2:-}"; shift 2 ;;
    --out) OUT="${2:-}"; shift 2 ;;
    --check) CHECK=1; shift ;;
    --stat) STAT=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown arg: $1" >&2; usage >&2; exit 2 ;;
  esac
done

[ -n "$HIST_DIR" ] && [ -d "$HIST_DIR/.git" ] || { echo "ERR not a buildhistory git repo: $HIST_DIR" >&2; exit 2; }
command -v git >/dev/null 2>&1 || { echo "ERR git not found" >&2; exit 2; }

[ -n "$REV1" ] || REV1="$(git -C "$HIST_DIR" rev-parse HEAD~1 2>/dev/null || true)"
[ -n "$REV2" ] || REV2="$(git -C "$HIST_DIR" rev-parse HEAD 2>/dev/null || true)"
[ -n "$REV1" ] && [ -n "$REV2" ] || { echo "ERR need two revisions (buildhistory 需至少两次构建)" >&2; exit 2; }
git -C "$HIST_DIR" rev-parse --verify "$REV1^{commit}" >/dev/null 2>&1 || { echo "ERR bad rev1=$REV1" >&2; exit 2; }
git -C "$HIST_DIR" rev-parse --verify "$REV2^{commit}" >/dev/null 2>&1 || { echo "ERR bad rev2=$REV2" >&2; exit 2; }
echo "BUILDHISTORY_DIFF_CONFIG dir=$HIST_DIR rev1=$REV1 rev2=$REV2"

TMP="$(mktemp)"
{
  echo "# buildhistory diff: $REV1 -> $REV2"
  echo "# generated by scripts/ci/buildhistory-diff.sh (YP-M1-S4 / D-06)"
  echo
  git -C "$HIST_DIR" diff "$REV1" "$REV2"
  if [ "$STAT" -eq 1 ]; then
    echo
    echo "# --- stat ---"
    git -C "$HIST_DIR" diff --stat "$REV1" "$REV2"
  fi
} >"$TMP" 2>&1
DIFF_RC=$?
[ "$DIFF_RC" -eq 0 ] || { echo "ERR git diff rc=$DIFF_RC" >&2; cat "$TMP" >&2; rm -f "$TMP"; exit 1; }

if [ -n "$OUT" ]; then
  mkdir -p "$(dirname "$OUT")"
  cp "$TMP" "$OUT"
  echo "BUILDHISTORY_ARCHIVED $OUT"
fi
cat "$TMP"

if [ "$CHECK" -eq 1 ]; then
  # diff 可读 = git diff 成功产出（空 diff 表示两次构建产物一致，属正常可复现）
  if grep -qE "^(diff --git|@@|\+|-)" "$TMP"; then
    echo "BUILDHISTORY_DIFF_OK readable-with-changes"
  else
    echo "BUILDHISTORY_DIFF_OK no-significant-change (两次构建产物一致，可复现)"
  fi
fi
rm -f "$TMP"
echo "BUILDHISTORY_DIFF_DONE"
exit 0
